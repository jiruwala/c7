alter trigger pass_vou2 disable;
DECLARE
BAL NUMBER;
PX NUMBER:=1;
CURSOR XX IS select cust_code, 
	   ACVOUCHER2.ACCNO,NAME,SUM(DEBIT-CREDIT) bal
	from
   back2025.acvoucher2	,back2025.ACACCOUNT WHERE ACACCOUNT.ACCNO=ACVOUCHER2.ACCNO 
   --and acvoucher2.flag=2
   GROUP BY ACVOUCHER2.ACCNO ,NAME,cust_code
having sum(debit)-sum(credit)!=0;
BEGIN  
DELETE FROM ACVOUCHER2 WHERE KEYFLD=-1;
DELETE FROM ACVOUCHER1 WHERE KEYFLD=-1;
INSERT INTO ACVOUCHER1(PERIODCODE,KEYFLD,YEAR,NO,DESCR,VOU_CODE,TYPE,VOU_DATE,CREATDT,FLAG) VALUES ('JAN_TO_MAR_2005',-1,'2003',1,'OPENING BALANCE 2025',1,1,TO_DATE('31/12/2025','DD/MM/RRRR'),SYSDATE,2);
FOR X IN XX
LOOP
IF X.BAL>=0 THEN
INSERT INTO ACVOUCHER2 (
   PERIODCODE, KEYFLD, NO, 
   VOU_CODE, VOU_DATE, POS, 
   ACCNO, DEBIT, CREDIT,fcdebit,fccredit ,
   DESCR, DESCR2, FLAG, 
   USERNM, CREATDT, YEAR, 
   TYPE, ISCHANGE, ISNEW, 
   INVOICE_CODE, INVOICE_TYPE, INVKEYFLD, 
   GRPNO, REFERNO, REFERCODE, 
   REFERTYPE, COSTCENT, REFERKEYFLD,cust_code)
VALUES (
   'JAN_TO_MAR_2005', -1,1, 
   1, TO_DATE('31/12/2025','DD/MM/RRRR'), PX, 
   X.ACCNO, X.BAL, 0, x.bal,0,
   'OPENING BALANCE', X.NAME, 2, 
   USER, SYSDATE, '2003', 
   1, 'Y', 'Y', 
   1, 1, NULL, 
   NULL, NULL, NULL, 
   NULL, NULL, NULL,x.cust_code);
ELSE
INSERT INTO ACVOUCHER2 (
   PERIODCODE, KEYFLD, NO, 
   VOU_CODE, VOU_DATE, POS, 
   ACCNO, DEBIT, CREDIT,fcdebit,fccredit, 
   DESCR, DESCR2, FLAG, 
   USERNM, CREATDT, YEAR, 
   TYPE, ISCHANGE, ISNEW, 
   INVOICE_CODE, INVOICE_TYPE, INVKEYFLD,
   GRPNO, REFERNO, REFERCODE, 
   REFERTYPE, COSTCENT, REFERKEYFLD,cust_code)
VALUES(
   'JAN_TO_MAR_2005', -1,1, 
   1, TO_DATE('31/12/2025','DD/MM/RRRR'), PX, 
   X.ACCNO, 0,ABS(X.BAL),0,abs(x.bal),
   'OPENING BALANCE', X.NAME, 2, 
   USER, SYSDATE, '2003', 
   1, 'Y', 'Y', 
   1, 1,NULL, 
   NULL, NULL, NULL, 
   NULL, NULL, NULL,x.cust_code);

END IF;
PX:=PX+1;         
END LOOP;
END;
/

alter trigger pass_vou2 enable ;

COMMIT;
